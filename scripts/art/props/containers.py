def bucket(v):
 a=Art('wood' if v==0 else 'metal',v);a.d.arc((12,10,35,34),180,360,fill=a.p[0],width=2);a.d.arc((13,10,34,32),190,345,fill=a.p[3],width=1)
 a.poly([(11,24),(36,24),(32,43),(16,43)],0);a.poly([(13,25),(34,25),(30,41),(17,41)],2)
 if v==0:
  for x in [17,23,29]:a.line((x,28,x,40),1);a.line((x+1,28,x+1,39),3)
  a.line((16,37,32,37),0,2)
 else:a.line((16,29,18,38),4,2);a.line((30,29,29,39),1,2)
 a.rim((11,20,36,29));return a.finish()

def modern(kind,v):
 a=Art('plastic' if kind=='plastic-bin' else 'metal' if kind=='metal-tin' else 'cloth',v)
