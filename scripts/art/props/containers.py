"""Hand-authored vessel, basket and box silhouettes composed from shared parts."""
from .common import Art, palette

def vessel(kind,v):
 a=Art('glaze' if kind=='glazed-jar' else 'metal' if kind=='metal-vessel' else 'clay',v)
 if kind in ['water-jug','amphora']:
  for x in ([9,30] if kind=='amphora' else [29]):
   a.ell((x,19,x+9,31),0);a.ell((x+1,20,x+8,29),2);a.ell((x+3,22,x+6,27),(0,0,0,0));a.line((x+2,21,x+3,20),4)
 if kind=='earthen-pot':
  a.poly([(13,25),(35,25),(36,30),(34,39),(30,43),(18,43),(14,39),(12,31)],0)
  a.poly([(14,27),(33,27),(34,32),(31,40),(19,41),(15,37)],2)
  a.poly([(15,28),(20,29),(19,37),(22,40),(18,39),(15,35)],3)
  a.poly([(31,29),(34,30),(32,39),(29,41),(22,41),(23,39),(29,38)],1)
  a.rim((12,21,35,29));a.specks([(19,32),(22,36),(28,31)],3)
 elif kind in ['storage-jar','glazed-jar']:
  a.poly([(17,16),(30,16),(34,21),(37,30),(35,39),(30,43),(17,43),(12,38),(11,29),(14,21)],0)
  a.poly([(17,18),(29,18),(33,23),(35,30),(32,40),(19,41),(14,36),(13,28)],2)
  a.poly([(16,24),(20,20),(22,20),(18,28),(18,36),(21,39),(17,38),(15,34)],3)
  a.poly([(31,23),(34,28),(34,35),(31,40),(23,41),(23,39),(29,38)],1)
  a.rim((15,14,32,20),False);a.ell((19,11,28,16),1);a.line((20,12,26,12),4)
  if kind=='glazed-jar':
   a.line((14,26,33,26),1);a.line((15,27,32,27),3);a.rect((16,29,18,32),4);a.rect((17,33,18,34),3)
  else:a.specks([(22,27),(27,32),(21,36),(29,22)],3)
 elif kind=='water-jug':
  a.poly([(19,15),(27,15),(27,24),(32,28),(34,35),(31,41),(26,43),(18,42),(14,36),(15,29),(19,24)],0)
  a.poly([(20,16),(25,16),(25,25),(30,29),(32,34),(28,40),(20,40),(16,35),(17,29),(21,25)],2)
  a.line((20,18,20,24,17,30,18,36,20,38),3,2);a.poly([(29,29),(32,34),(29,40),(22,40),(24,38),(28,36)],1)
  a.rim((17,12,29,18))
 elif kind=='amphora':
  a.poly([(19,11),(28,11),(28,20),(33,25),(33,34),(29,39),(26,43),(21,43),(18,39),(14,34),(14,26),(19,20)],0)
  a.poly([(20,14),(26,14),(26,21),(31,26),(31,33),(27,38),(24,41),(22,40),(20,37),(16,32),(16,26),(21,20)],2)
  a.line((20,22,17,27,18,33,22,38),3,2);a.poly([(28,24),(31,27),(31,33),(26,39),(24,39),(28,32)],1)
  a.rim((17,9,30,15),False);a.rect((20,8,27,10),1);a.line((21,8,26,8),3)
  a.rect((16,42,31,44),'#594631');a.line((17,42,21,39),'#a38353',2);a.line((30,42,27,39),'#a38353',2)
 else:
  a.poly([(20,18),(28,18),(30,25),(34,29),(34,37),(30,42),(17,42),(13,36),(14,29),(19,25)],0)
  a.poly([(20,21),(27,21),(28,26),(32,30),(32,36),(28,40),(19,40),(15,35),(16,29),(21,26)],2)
  a.poly([(17,29),(20,27),(21,28),(18,32),(19,36),(21,38),(17,37),(16,33)],4)
  a.poly([(29,28),(32,30),(32,37),(28,40),(23,40),(25,38),(29,36)],1)
  a.rim((16,15,32,22));a.line((18,39,29,39),3)
 return a.finish()

def gourd(v):
 a=Art('clay',v);a.ell((12,24,34,43),0);a.ell((13,24,32,41),2);a.ell((17,15,28,32),0);a.ell((18,16,27,32),2)
 a.line((19,22,18,29,16,32,16,37),3,2);a.ell((19,13,26,19),3);a.ell((20,14,25,17),0)
 a.line((27,18,34,22,37,32,34,36),'#c5b584');a.specks([(24,34),(28,30),(20,39),(23,23),(29,37)],1)
 return a.finish()

def basket(kind,v):
 a=Art('fiber',v);lid=kind=='lidded-basket'; y=19 if lid else 30
 a.poly([(8,y),(39,y),(35,42),(14,43)],0);a.poly([(10,y+1),(36,y+1),(33,40),(15,41)],2)
 for yy in range(y+3,41,3):
  a.line((12,yy,34,yy),1);a.line((14,yy+1,31,yy+1),3)
 for xx in range(16,34,5):
  a.line((xx,y+3,xx-1,39),3);a.line((xx+1,y+4,xx,39),1)
 a.rim((8,y-5,39,y+5),not lid)
 if lid:
  a.line((13,y-3,34,y-3),4);a.ell((21,y-8,28,y-3),0);a.ell((23,y-7,26,y-4),3)
  for xx in [14,31]:a.line((xx,y+4,xx,40),0);a.line((xx+1,y+4,xx+1,40),3)
 return a.finish()

