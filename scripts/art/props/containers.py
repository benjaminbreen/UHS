def box(kind,v):
 a=Art('wood',v);top=23 if kind=='plain-box' else 18;bottom=41
 if kind=='painted-chest':
  c=palette('cloth',[1,2,0][v])
  for x in [12,29]:a.rect((x,34,x+3,43),0);a.line((x+1,36,x+1,41),3)
  a.poly([(10,17),(29,17),(37,22),(37,37),(29,40),(10,37)],0)
  a.rect((11,22,29,37),2);a.poly([(30,22),(36,23),(36,36),(30,38)],1)
  a.rect((13,24,27,34),c[0]);a.rect((14,25,26,33),c[2]);a.line((15,25,25,25),c[3])
  a.poly([(10,17),(29,17),(36,21),(29,23),(10,21)],3);a.line((12,17,28,17),4)
  a.rect((18,23,22,27),0);a.rect((19,23,21,25),'#d5b978')
  a.poly([(19,29),(21,27),(23,29),(21,31)],c[3]);a.line((12,36,28,36),4)
  return a.finish()
 a.poly([(8,top),(30,top),(40,top+5),(40,bottom-2),(31,44),(8,40)],0)
 a.planks((9,top+5,31,40));a.poly([(32,top+5),(39,top+6),(39,39),(32,42)],1)
 a.poly([(9,top),(30,top),(38,top+4),(31,top+6),(9,top+4)],3);a.line((10,top,29,top),4)
 for x in [16,24]:a.line((x,top+1,x+4,top+4),2)
 if kind=='bound-chest':
  for x in [12,26]:a.rect((x,top+5,x+2,39),'#3a403c');a.line((x,top+6,x,38),'#879078');a.rect((x,top,x+2,top+4),'#626953');a.rect((x+1,top+8,x+1,top+8),'#c3bea0')
  a.rect((19,top+7,23,top+13),'#3b3730');a.rect((20,top+7,22,top+11),'#c8b27d');a.rect((21,top+10,21,top+12),'#4c4538')
 if kind=='crate':
  for yy in [top+9,top+16]:a.rect((11,yy,29,yy+2),(0,0,0,0));a.line((11,yy+3,29,yy+3),4)
  for x in [9,29]:a.rect((x,top+5,x+2,40),3);a.line((x,top+6,x,39),4)
  a.line((12,38,27,top+7),1,3);a.line((12,37,27,top+6),3,2)
 return a.finish()

def barrel(v):
 a=Art('wood',v);a.poly([(16,13),(31,13),(35,23),(35,35),(31,43),(16,43),(12,34),(12,24)],0)
 a.poly([(17,15),(30,15),(33,24),(33,35),(29,41),(17,41),(14,34),(14,24)],2)
 for x in [18,23,28]:a.line((x,17,x-1,28,x,40),1);a.line((x+1,18,x,28,x+1,38),3)
 a.rim((15,10,32,18),False);a.line((17,13,28,13),1);a.line((20,12,22,16),2)
 for y in [21,35]:a.line((14,y,32,y),0,3);a.line((14,y-1,32,y-1),'#89917b');a.line((14,y+1,32,y+1),'#4d554b')
