def furniture(kind,v):
 a=Art('wood',v)
 if kind=='stool':
  for x,y,dx in [(15,31,-2),(28,30,2),(22,28,0)]:a.line((x,y,x+dx,43),0,4);a.line((x,y,x+dx,41),2,2)
