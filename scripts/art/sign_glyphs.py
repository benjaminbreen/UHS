"""Shop lettering in scripts the runtime's 3x5 font cannot draw, rendered once
from macOS system fonts to bitmaps the game draws signs with.

    .venv/bin/python scripts/art/sign_glyphs.py

Reads src/content/settlements/sign-words.json and writes
src/render/sign-glyphs.generated.ts. Arabic and Persian are joined here (this
PIL has no shaping library) by swapping each letter for its presentation form,
then drawn whole word by whole word; Chinese and Japanese are drawn a
character at a time, so the game can stack them for a vertical board.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent.parent
ARABIC_FONT = '/System/Library/Fonts/SFArabic.ttf'
CJK_FONT = '/System/Library/Fonts/STHeiti Medium.ttc'
# (font size, threshold): the two sizes a board can take.
SIZES = {'arabic': ((10, 105), (13, 115)), 'cjk': ((10, 110), (12, 120))}

# Letter -> first presentation form; four-form letters run isolated, final,
# initial, medial; two-form letters only isolated and final.
FOUR = {'ئ': 0xFE89, 'ب': 0xFE8F, 'ت': 0xFE95, 'ث': 0xFE99, 'ج': 0xFE9D, 'ح': 0xFEA1, 'خ': 0xFEA5, 'س': 0xFEB1,
        'ش': 0xFEB5, 'ص': 0xFEB9, 'ض': 0xFEBD, 'ط': 0xFEC1, 'ظ': 0xFEC5, 'ع': 0xFEC9, 'غ': 0xFECD, 'ف': 0xFED1,
        'ق': 0xFED5, 'ك': 0xFED9, 'ل': 0xFEDD, 'م': 0xFEE1, 'ن': 0xFEE5, 'ه': 0xFEE9, 'ي': 0xFEF1,
        'پ': 0xFB56, 'چ': 0xFB7A, 'ک': 0xFB8E, 'گ': 0xFB92, 'ی': 0xFBFC}
TWO = {'آ': 0xFE81, 'أ': 0xFE83, 'ؤ': 0xFE85, 'إ': 0xFE87, 'ا': 0xFE8D, 'ة': 0xFE93, 'د': 0xFEA9, 'ذ': 0xFEAB,
       'ر': 0xFEAD, 'ز': 0xFEAF, 'و': 0xFEED, 'ى': 0xFEEF, 'ژ': 0xFB8A}
LAM_ALEF = {'ا': 0xFEFB, 'أ': 0xFEF7, 'إ': 0xFEF9, 'آ': 0xFEF5}


def shape(word):
    """Visual order, left to right, each letter in its joined form."""
    out, i = [], 0
    while i < len(word):
        ch = word[i]
        joins = i > 0 and word[i - 1] in FOUR
        if ch == 'ل' and i + 1 < len(word) and word[i + 1] in LAM_ALEF:
            out.append(chr(LAM_ALEF[word[i + 1]] + joins))
            i += 2
            continue
        nxt = i + 1 < len(word) and (word[i + 1] in FOUR or word[i + 1] in TWO)
        if ch in FOUR:
            out.append(chr(FOUR[ch] + (3 if joins and nxt else 1 if joins else 2 if nxt else 0)))
        elif ch in TWO:
            out.append(chr(TWO[ch] + joins))
        else:
            out.append(ch)
        i += 1
    return ''.join(reversed(out))


def draw(text, font, size, thr):
    f = ImageFont.truetype(font, size)
    im = Image.new('L', (size * (len(text) + 2) * 2, size * 3), 0)
    ImageDraw.Draw(im).text((size, size), text, font=f, fill=255)
    return im.point(lambda v: 255 if v > thr else 0)


def pack(items, own=False):
    """Crop every bitmap of one size to the same rows, so characters share a
    baseline; or, for whole words (`own`), each to its own ink."""
    boxes = [im.getbbox() for im in items.values() if im.getbbox()]
    top, bottom = min(b[1] for b in boxes), max(b[3] for b in boxes)
    out = {}
    for key, im in items.items():
        b = im.getbbox()
        if not b:
            continue
        cut = im.crop((b[0], b[1] if own else top, b[2], b[3] if own else bottom))
        rows = []
        for y in range(cut.height):
            bits = ''.join('1' if cut.getpixel((x, y)) else '0' for x in range(cut.width))
            rows.append(format(int(bits, 2), 'x').zfill((cut.width + 3) // 4))
        out[key] = [cut.width, cut.height, rows]
    return out


def main():
    words = json.loads((ROOT / 'src/content/settlements/sign-words.json').read_text())
    arabic, cjk = set(), set()
    for trade, langs in words.items():
        if trade == '_':
            continue
        for lang, ws in langs.items():
            for w in ws:
                if lang in ('ar', 'fa'):
                    arabic.add(w)
                else:
                    cjk.update(w)
    out = {}
    for size, thr in SIZES['arabic']:
        for k, v in pack({w: draw(shape(w), ARABIC_FONT, size, thr) for w in sorted(arabic)}, own=True).items():
            out[f'{size}:{k}'] = v
    for size, thr in SIZES['cjk']:
        cells = pack({ch: draw(ch, CJK_FONT, size, thr) for ch in sorted(cjk)})
        for k, (w, h, rows) in cells.items():
            out[f'{size}:{k}'] = [w, h, rows]
    body = json.dumps(out, ensure_ascii=False, separators=(',', ':'))
    (ROOT / 'src/render/sign-glyphs.generated.ts').write_text(
        '// Generated by scripts/art/sign_glyphs.py from src/content/settlements/sign-words.json. Do not edit.\n'
        '// "size:text" -> [width, height, rows as hex, high bit leftmost].\n'
        f'export const SCRIPT_BITMAPS: Record<string, [number, number, string[]]> = {body};\n'
        f'export const ARABIC_SIZES = {json.dumps([s for s, _ in SIZES["arabic"]])};\n'
        f'export const CJK_SIZES = {json.dumps([s for s, _ in SIZES["cjk"]])};\n')
    print(f'{len(out)} bitmaps')


if __name__ == '__main__':
    main()


