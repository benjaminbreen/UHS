# A rough copy of src/render/shop-signs.ts, so review sheets show signs where
# the game will draw them. The game's own drawing is the one that counts.

PAINTS = {'ar': ['#2f6b4f', '#b33a2e', '#2a4f8f', '#e0b23c', '#ece4cf', '#1f6f74', '#6b3a2a'],
          'zh': ['#b8262c', '#1d5a3a', '#d9a632', '#1e3557', '#f2e8d0', '#2b2b2b'],
          'ja': ['#f2ecdc', '#1f3b6a', '#c43c2e', '#2e6b4a', '#e9c54a', '#30303a']}
_CACHE = {}


def _bitmaps():
    if not _CACHE:
        src = (ROOT / 'src/render/sign-glyphs.generated.ts').read_text()
        body = src.split('= ', 1)[1].split(';\n', 1)[0]
        _CACHE.update(json.loads(body))
    return _CACHE


def _bits(key):
    got = _bitmaps().get(key)
    if not got:
        return None
    w, h, rows = got
    out = []
    for row in rows:
        pad = len(row) * 4 - w
        out.append([(int(row[(x + pad) >> 2], 16) >> (3 - ((x + pad) & 3))) & 1 for x in range(w)])
    return w, h, out


def preview(im, slots, lang='ar', seed=0):
    """Paint the signs a street in `lang` might hang in these slots."""
    import random
    words = json.loads((ROOT / 'src/content/settlements/sign-words.json').read_text())
    trades = [k for k in words if k != '_']
    rng = random.Random(seed)
    px = im.load()
    for x, y, w, h, kind, *hint in slots:
        if rng.random() < 0.12:
            continue
        trade = hint[0] if hint and hint[0] in words else rng.choice(trades)
        vertical = kind == 'blade' or h > w * 1.6
        pad = {'box': 3, 'paint': 0}.get(kind, 2)
        best = None
        for word in words[trade].get(lang, []):
            sizes = (13, 10) if lang in ('ar', 'fa') else (12, 10)
            for size in sizes:
                if lang in ('ar', 'fa'):
                    got = None if vertical else _bits(f'{size}:{word}')
                else:
                    cells = [_bits(f'{size}:{ch}') for ch in word]
                    got = None
                    if all(cells):
                        if vertical:
                            cw, ch_ = max(c[0] for c in cells), sum(c[1] + 1 for c in cells) - 1
                            rows = [[0] * cw for _ in range(ch_)]
                            at = 0
                            for cell in cells:
                                for yy in range(cell[1]):
                                    for xx in range(cell[0]):
                                        rows[at + yy][(cw - cell[0]) // 2 + xx] |= cell[2][yy][xx]
                                at += cell[1] + 1
                        else:
                            cw, ch_ = sum(c[0] + 1 for c in cells) - 1, max(c[1] for c in cells)
                            rows = [[0] * cw for _ in range(ch_)]
                            at = 0
                            for cell in cells:
                                for yy in range(cell[1]):
                                    for xx in range(cell[0]):
                                        rows[yy][at + xx] |= cell[2][yy][xx]
                                at += cell[0] + 1
                        got = (cw, ch_, rows)
                if got and got[0] <= w - 2 * pad and got[1] <= h - 2 * pad:
                    best = got
                    break
            if best:
                break
        if not best:
            continue
        hexc = rng.choice(PAINTS.get(lang, PAINTS['ar']))
        paint = tuple(int(hexc[i:i + 2], 16) for i in (1, 3, 5))
        lightish = 0.299 * paint[0] + 0.587 * paint[1] + 0.114 * paint[2] > 140
        dark = tuple(int(v * 0.5) for v in paint)
        if kind == 'paint':
            ink, shadow = paint, dark
        else:
            for yy in range(h):
                for xx in range(w):
                    edge = xx in (0, w - 1) or yy in (0, h - 1)
                    col = dark if edge else tuple(min(255, int(v * 1.2)) for v in paint) if yy == 1 else paint
                    px[x + xx, y + yy] = col + (255,)
            ink = (40, 30, 24) if lightish else (244, 234, 208)
            shadow = tuple(int(v * 0.68) for v in paint)
        bw, bh, rows = best
        tx, ty = x + (w - bw) // 2, y + (h - bh) // 2
        for yy in range(bh):
            for xx in range(bw):
                if rows[yy][xx]:
                    if yy + 1 >= bh or not rows[yy + 1][xx]:
                        px[tx + xx, ty + yy + 1] = shadow + (255,)
        for yy in range(bh):
            for xx in range(bw):
                if rows[yy][xx]:
                    px[tx + xx, ty + yy] = ink + (255,)
    return im
