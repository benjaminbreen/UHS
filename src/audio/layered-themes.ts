import type { CultureId } from "../content/history/types";
import type { Stem, Voice } from "./score";

/** One repeating line. Its length is its own; it need not divide the bar. */
export interface Layer {
  voice: Voice;
  stem: Stem;
  /** "pitch:beats" tokens, looped from `enter` until `exit`; "A3+C4+E4:1" strums a chord. */
  loop: string;
  velocity: number;
  enter?: number;
  exit?: number;
  pan?: number;
  transpose?: number;
  /** Silent at night and dawn. */
  day?: boolean;
  /** Tape echo: repeats every `beats`, `count` times, each `feedback` times quieter. */
  echo?: [beats: number, count: number, feedback: number];
  /** Each repetition starts this many beats early, so the loop slowly phases against the others. */
  drift?: number;
}

/** A piece whose form comes from loops entering and leaving, not from set sections. */
export interface LayeredTheme {
  id: string;
  title: string;
  subtitle: string;
  place: string;
  culture: CultureId | CultureId[];
  years: [number, number];
  evidence: string;
  bpm: number;
  meter: number;
  bars: number;
  key: string;
  /** Cents offset per pitch class, 0 = C. */
  tuning?: Record<number, number>;
  /** Delay every off-beat of this subdivision (0.5 = eighths) by `amount` beats. */
  swing?: [unit: number, amount: number];
  /** Reverb send and length in seconds; default a modest room. */
  reverb?: [number, number];
  layers: Layer[];
}

