import type { CultureId } from "../content/history/types";
import { layeredThemes } from "./layered-themes";
import type { Voice } from "./score";

export interface CulturalTheme {
  id: string;
  title: string;
  subtitle: string;
  place: string;
  culture: CultureId;
  /** Years in which the setting is a direct hit and the piece plays first. */
  years: [number, number];
  /** Documented / inferred / fictional basis, kept beside the notes it justifies. */
  evidence: string;
  bpm: number;
  /** Beats per bar; phrases use the same "pitch:beats" tokens as the default themes. */
  meter: number;
  key: string;
  melody: string[];
  bridge: string[];
  chords: string[];
  bridgeChords: string[];
  lead: Voice;
  nightLead?: Voice;
  answer: Voice;
  /** Answer doubles the melody instead of playing a countermelody. */
  heterophony?: boolean;
  /** Semitones from the melody for the heterophonic answer; default an octave down. */
  answerOctave?: number;
  /** Answer plays at double density an octave up, alternating with the upper neighbour (bonang-style). */
  elaborate?: boolean;
  accompany: Voice;
  /** [beat within bar, chord tone], sounded an octave above the chord. */
  pattern: [number, number][];
  /** Sounds only when the chord root changes, unless a groove is written. */
  bass?: Voice;
  /** A bass line per bar, in melody tokens, played on `bass`. */
  groove?: string[];
  bridgeGroove?: string[];
  /** Sections (0–3) in which the melody plays; default all. */
  melodySections?: number[];
  /** Every bar, twice in even meters; for drum-led pieces. */
  steadyBass?: Voice;
  drone?: boolean;
  droneVoice?: Voice;
  /** [beat within bar, voice, midi, velocity, every n bars (on the last of each n)]. */
  drums: [number, Voice, number, number, number?][];
  /** Sounded at the start of each eight-bar phrase. */
  mark?: [Voice, number];
  /** Cents offset per pitch class, 0 = C. */
  tuning?: Record<number, number>;
  grace?: boolean;
}

