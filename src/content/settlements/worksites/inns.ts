const MEAL_INCLUDED = new Set(["edo-hatago", "grand-ryokan", "inca-tambo", "dharamshala"]);

export function innProfileFor(claim: string | undefined): WorksiteProfile | undefined {
  if (!claim?.startsWith("worksite-") || claim.endsWith("-store")) return undefined;
  const id = claim.slice(9);
  return innProfiles.find((p) => p.id === id);
}

export function innTerms(profile: WorksiteProfile, nightsStayed: number, coined: boolean) {
  const spec = profile.inn!;
  const endowedLeft = spec.endowment === "free" ? Math.max(0, 3 - nightsStayed) : 0;
  const gift = spec.endowment === "gift";
  const grand = spec.plan === "corridor";
  const roomCost = !coined || endowedLeft > 0 || gift ? 0 : grand ? 2 : 1;
  const mealIncluded = MEAL_INCLUDED.has(profile.id);
  const mealCost = !coined || mealIncluded || endowedLeft > 0 || gift ? 0 : 1;
  const mealName = MEALS[profile.id] ?? "a hot meal and bread";
  const format = (coins: number, withMeal: boolean) => {
    if (endowedLeft > 0) return `Free · ${endowedLeft} endowed night${endowedLeft === 1 ? "" : "s"} left`;
    if (gift || !coined) return withMeal || mealIncluded ? "Hospitality · supper & bed" : "Hospitality";
    const base = `${coins} coin${coins === 1 ? "" : "s"}`;
    return mealIncluded ? `${base} · supper included` : base;
  };
  return {
    roomCost,
    mealCost,
    mealIncluded,
    mealName,
    endowedLeft,
    gift,
    grand,
    roomLabel: format(roomCost, false),
    mealLabel: format(roomCost + mealCost, true),
  };
}
