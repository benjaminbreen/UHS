/** Undefined before the first estimate: the city is not yet attested there. */
export function cityPopulation(placeId: string, year: number) {
  const s = series[placeId];
  if (!s || year < s[0][0]) return;
  const i = s.findIndex(([y]) => y > year);
  if (i < 0) return s[s.length - 1][1];
  const [y0, p0] = s[i - 1],
    [y1, p1] = s[i];
  return Math.round(p0 + ((p1 - p0) * (year - y0)) / (y1 - y0));
}
