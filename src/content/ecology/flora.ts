/**
 * Named wild plants: which grow where, how a bloom is drawn, and what a cut
 * one gives up. Picks are hashed from world position, so the renderer, the
 * hover label and the engine's harvest always agree on the plant.
 */
import type { ItemDef, ItemId } from "../../core/types";
import { waterHash as hash } from "../../core/water-field";
import type { Ecology } from "./profiles";

export type FloraRegion =
  | "europe"
  | "med"
  | "westasia"
  | "southasia"
  | "eastasia"
  | "seasia"
  | "northasia"
  | "africa"
  | "safrica"
  | "naeast"
  | "nawest"
  | "mesoamerica"
  | "samerica"
  | "australia";
/** Where a plant grows. `*` for the cosmopolitan and circumpolar ones. */
type Range = FloraRegion | "*";
/** Siberia shares its flora with both ends of the Palearctic. */
const alias: Partial<Record<FloraRegion, FloraRegion[]>> = {
  northasia: ["europe", "eastasia"],
};
const inBox = (
  lon: number,
  lat: number,
  w: number,
  s: number,
  e: number,
  n: number,
) => lon >= w && lon <= e && lat >= s && lat <= n;
export function floraRegion(lon: number, lat: number): FloraRegion {
  if (inBox(lon, lat, 110, -50, 180, -10)) return "australia";
  if (lon < -30) {
    if (lat > 25 || (lat > 15 && lon < -118))
      return lon < -100 ? "nawest" : "naeast";
    return lat > 5 ? "mesoamerica" : "samerica";
  }
  if (lat >= 50 && lon >= 60) return "northasia";
  if (lon > 92 && lat > 20) return "eastasia";
  // The steppe and the Tarim belong with Iran, not with Europe or India.
  if (lon >= 55 && lat >= 35) return "westasia";
  if (lat >= 45) return "europe";
  if (inBox(lon, lat, 60, 5, 92, 35)) return "southasia";
  if (inBox(lon, lat, -18, 27, 36, 45)) return "med";
  if (inBox(lon, lat, 35, 12, 75, 50)) return "westasia";
  if (inBox(lon, lat, 92, 20, 150, 55)) return "eastasia";
  if (inBox(lon, lat, 92, -11, 160, 20)) return "seasia";
  if (lat < 30 && lon < 55) return lat < -22 ? "safrica" : "africa";
  return "europe";
}

/** What kind of growth a species stands in for. Sprites map onto these. */
export type FloraForm =
  | "bloom"
  | "shrub"
  | "heath"
  | "scrub"
  | "grass"
  | "reed"
  | "fern";
export type BloomHabit = "head" | "spike" | "umbel" | "mat" | "bell";
export type BloomLook = {
  habit: BloomHabit;
  petal: string;
  centre: string;
  /** Stem height: -1 low, 0 middling, 1 tall. */
  size: -1 | 0 | 1;
};
/** Item, chance per cut, count. A chance of 1 always yields. */
type Yield = readonly [ItemId, number, number?];
export type Species = {
  id: string;
  common: string;
  latin: string;
  form: FloraForm;
  range: Range[];
  eco?: Ecology[];
  weight: number;
  yields: Yield[];
  look?: BloomLook;
};

const G: Ecology = "grassland",
  S: Ecology = "dry-scrub",
  T: Ecology = "temperate-woodland",
  B: Ecology = "boreal-woodland",
  R: Ecology = "tropical-woodland",
  W: Ecology = "wetland",
  V: Ecology = "savanna",
  N: Ecology = "tundra",
  D: Ecology = "desert";
const look = (
  habit: BloomHabit,
  petal: string,
  centre: string,
  size: -1 | 0 | 1 = 0,
): BloomLook => ({ habit, petal, centre, size });
const sp = (
  id: string,
  common: string,
  latin: string,
  form: FloraForm,
  range: Range[],
  eco: Ecology[] | undefined,
  weight: number,
  yields: Yield[] = [],
  bloom?: BloomLook,
): Species => ({
  id,
  common,
  latin,
  form,
  range,
  eco,
  weight,
  yields,
  look: bloom,
});

