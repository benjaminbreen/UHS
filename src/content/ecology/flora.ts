/** Heath and scrub borrow from shrubs where a region has none of their own. */
const fallback: Partial<Record<FloraForm, FloraForm>> = {
  heath: "shrub",
  scrub: "shrub",
};
const neighbours: Partial<Record<Ecology, Ecology[]>> = {
  grassland: [T, V, S],
  "dry-scrub": [V, G, D],
  "temperate-woodland": [G, B, W],
  "boreal-woodland": [N, T],
  "tropical-woodland": [V, W],
  wetland: [T, R, G],
  savanna: [S, G, R],
  tundra: [B],
  desert: [S, V],
};
const pools = new Map<string, Species[]>();
function pool(
  form: FloraForm,
  region: FloraRegion,
  ecology: Ecology,
): Species[] {
  const key = `${form}:${region}:${ecology}`;
  let found = pools.get(key);
  if (found) return found;
  const regions = alias[region] ?? [region];
  const here = (s: Species) =>
    s.form === form && s.range.some((r) => r === "*" || regions.includes(r));
  const fits = (s: Species) => !s.eco || s.eco.includes(ecology);
  const local = flora.filter(here);
  found = local.filter(fits);
  // Too few fit to keep a rarity rare: let in what grows in the nearest
  // ecologies, nearest first, and only then the rest of the region. A desert
  // borrows from dry scrub before it borrows a forest ginger.
  const weight = () => found!.reduce((n, s) => n + s.weight, 0);
  for (const near of neighbours[ecology] ?? []) {
    if (weight() >= 4) break;
    found = [
      ...new Set([
        ...found,
        ...local.filter((s) => s.eco?.includes(near) && !s.range.includes("*")),
      ]),
    ];
  }
  if (!found.length) found = local.filter((s) => !s.range.includes("*"));
  if (!found.length && fallback[form])
    found = pool(fallback[form]!, region, ecology);
  pools.set(key, found);
  return found;
}
/** A weighted pick. `roll` is 0-1. */
export function pickSpecies(
  form: FloraForm,
  region: FloraRegion,
  ecology: Ecology,
  roll: number,
): Species | undefined {
  const list = pool(form, region, ecology);
  if (!list.length) return undefined;
  const total = list.reduce((n, s) => n + s.weight, 0);
  let r = roll * total;
  for (const s of list) if ((r -= s.weight) < 0) return s;
  return list.at(-1);
}
/** The plant standing on a cell, from its decoration sprite. */
export function speciesAt(
  sprite: string | undefined,
  region: FloraRegion,
  ecology: Ecology,
  x: number,
  y: number,
) {
  const form = floraForm(sprite);
  return form && pickSpecies(form, region, ecology, hash(x, y, 811));
}
