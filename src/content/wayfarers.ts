/** Who might come down the road here and now, each with its weight. */
export function wayfarersAt(setting: WorldSetting) {
  const shares = subsistenceFor(setting)?.shares;
  // Before farming began anywhere, whatever the regional tables say.
  const foraging = (shares?.foraging ?? 0) >= 0.5 || setting.year < -9000;
  return wayfarers.filter(
    (w) =>
      matchesCharacterScope(w.scope, setting, "*") &&
      (w.lifeway === "any" || (w.lifeway === "foraging") === foraging),
  );
}
