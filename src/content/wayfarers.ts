/** People met on the road between places, rather than living in one. The
 * work of the countryside itself (wood, roots, honey, game) is the livelihood
 * tables' `wild` rows; this is everyone else who passes through. */
export type Wayfarer = {
  id: string;
  scope: CharacterScope;
  label: string;
  /** The livelihood they dress and carry as. */
  dress: string;
  /** While walking toward a named place; `{to}` is its name. */
  going?: string;
  /** While walking anywhere else. */
  doing: string;
  /** What they stop for on the way, if anything. A trader stops where there
   * are people to sell to. */
  halt?: "rest" | "trade" | "talk";
  carry?: "bundle" | "basket" | "vessel";
  /** Chance of one, two or three in the party. */
  party: readonly [number, number, number];
  women: number;
  youth?: number;
  /** Tiles per walking tile's time: a runner is quicker than a family. */
  speed?: number;
  /** The pack animals they drive: a fauna species, and how many. */
  animal?: { species: string; count: readonly [number, number] };
  /** Who meets them: farmers and herders unless it says otherwise. */
  lifeway?: "foraging" | "any";
  weight: number;
  /** Documented, inferred or hypothetical, and on what. */
  note: string;
};

